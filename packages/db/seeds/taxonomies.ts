export type SkillSeed = {
  name: string;
  slug: string;
  functionalArea: FunctionalArea;
  aliases: string[];
};

export const SKILLS: SkillSeed[] = FUNCTIONAL_AREAS.flatMap((area) =>
  SKILLS_BY_AREA[area].map((name) => ({
    name,
    slug: slugify(name),
    functionalArea: area,
    aliases: [],
  })),
);

