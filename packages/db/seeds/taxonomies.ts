// Names whose punctuation-stripped slug would otherwise collide
// (e.g. "C++" and "C#" both reduce to "c").
const SLUG_OVERRIDES: Record<string, string> = {
  "C++": "cpp",
  "C#": "csharp",
};

function slugify(name: string): string {
  if (SLUG_OVERRIDES[name]) return SLUG_OVERRIDES[name];
  return name
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-+|-+$/g, "");
}

